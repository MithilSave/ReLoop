/**
 * Allocation → run → source batch lineage, built from passports.
 * EPR users cannot read processing records directly; each passport lists the runs a batch fed and the
 * allocation ids (yours only) on those runs. A batch's share of an allocation is pro rata by its output share
 * (Assumption A-10), with run output = sum of apportioned output across the run's batches.
 */
export interface LineageRow { allocation: Allocation; batchCode: string; recordCode: string; shareKg: number; decision: NgoDecision | null; batchStatus: string; locality: string | null }
export function useAllocationLineage() {
  const allocations = useAllocations()
  const batches = useBatches({ status: 'PROCESSED' })
  const codes = (batches.data ?? []).map((b) => b.batch_code)
  const ps = useQueries({ queries: codes.map((c) => ({ queryKey: K.passport(c), queryFn: () => fetchPassport(c) })) })
  const loading = allocations.isPending || batches.isPending || ps.some((p) => p.isPending)
  const error = allocations.error ?? batches.error ?? ps.find((p) => p.error)?.error ?? null
  const rows = React.useMemo<LineageRow[]>(() => {
    if (loading || error) return []
    const passports = ps.map((p) => p.data).filter(Boolean) as Passport[]
    const runOut = new Map<string, number>()
    passports.forEach((p) => p.custody.processing_runs.forEach((r) => runOut.set(r.record_code, (runOut.get(r.record_code) ?? 0) + r.apportioned_output_kg)))
    const out: LineageRow[] = []
    for (const a of (allocations.data ?? []).filter((x) => x.status === 'ACTIVE')) {
      for (const p of passports) {
        if (!p.epr_allocations.some((e) => e.allocation_id === a.id)) continue
        const cur = p.verifications.find((v) => v.is_current)
        for (const r of p.custody.processing_runs) {
          const total = runOut.get(r.record_code) ?? 0
          if (!total) continue
          out.push({ allocation: a, batchCode: p.batch_code, recordCode: r.record_code, shareKg: (a.quantity_kg * r.apportioned_output_kg) / total, decision: cur?.decision ?? null, batchStatus: p.status, locality: p.generator.locality })
        }
      }
    }
    return out
  }, [loading, error, allocations.data, ps])
  return { rows, loading, error, allocations, refetch: () => { void allocations.refetch(); void batches.refetch() } }
}
const split = (rows: LineageRow[]) => ({
  verified: rows.filter((r) => r.decision === 'VERIFIED').reduce((s, r) => s + r.shareKg, 0),
  concern: rows.filter((r) => r.decision && ['FLAGGED', 'REJECTED', 'REQUIRES_CORRECTION'].includes(r.decision)).reduce((s, r) => s + r.shareKg, 0),
  pending: rows.filter((r) => !r.decision || ['PENDING', 'UNDER_REVIEW'].includes(r.decision)).reduce((s, r) => s + r.shareKg, 0),
})

/* ─────────────── Overview ─────────────── */
export function EprOverview() {
  const [period, setPeriod] = React.useState(currentReportingPeriod())
  const dash = useEprDashboard(period)
  const targets = useTargets()
  const lin = useAllocationLineage()
  const disc = useEprDiscrepancies()
  const periods = [...new Set([currentReportingPeriod(), ...(targets.data ?? []).map((t) => t.reporting_period)])]
  return (
    <>
      <PageHeader title="Compliance overview" description="Recycling quantities attributed to your organisation against your self-declared targets, split by independent verification status."
        actions={<><Select aria-label="Reporting period" value={period} onChange={(e) => setPeriod(e.target.value)} className="w-36">{periods.map((p) => <option key={p}>{p}</option>)}</Select><Button variant="outline" asChild><Link to="/e/reports"><Download />Reports</Link></Button></>} />
      <Note tone="warn" className="mb-4" title="Scope">{BOUNDARY}</Note>
      <QueryState query={dash}>{(d) => {
        const rows = lin.rows.filter((r) => r.allocation.reporting_period === period)
        const s = split(rows)
        const openDisc = (disc.data ?? []).filter((x) => x.status === 'OPEN')
        return (
          <div className="flex flex-col gap-4">
            <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
              <Kpi icon={<Link2 />} label="Allocated to you" value={kg(d.total_allocated_kg)} sub={d.total_target_kg ? `${pct(d.compliance_pct)} of ${kg(d.total_target_kg)} self-declared` : 'No targets set for this period'} />
              <Kpi icon={<ShieldCheck />} label="From NGO-verified batches" value={lin.loading ? '…' : kg(s.verified)} sub="Computed per source batch" />
              <Kpi label="Awaiting NGO review" value={lin.loading ? '…' : kg(s.pending)} sub="Allocated, not yet verified" />
              <Kpi icon={<AlertTriangle />} label="Linked to flagged evidence" value={lin.loading ? '…' : kg(s.concern)} sub={`${openDisc.length} open discrepancy flag${openDisc.length === 1 ? '' : 's'}`} />
            </div>
            {s.concern > 0 && <Note tone="bad">{kg(s.concern)} allocated to you comes from batches an NGO flagged, rejected or sent back for correction. Review before relying on it. <Link to="/e/discrepancies" className="font-medium underline">Open discrepancies</Link></Note>}
            {Math.abs(d.verified_allocated_kg - s.verified) > 0.5 && !lin.loading && (
              <Note>The backend’s own dashboard reports {kg(d.verified_allocated_kg)} as verified because it counts a whole allocation once any source batch is verified (audit D7). The figure above attributes each allocation to its source batches and counts only the verified share.</Note>
            )}
            <Panel title="Progress by packaging category" sub="kg · bar length = your target" footer={<SourceLine source="ReLoop API · /epr/dashboard, /epr/allocations, /passports" period={period} />}>
              {d.targets_by_category.length === 0 ? <EmptyState title="No targets for this period" action={<Button size="sm" asChild><Link to="/e/obligations"><Target />Set targets</Link></Button>} /> : (
                <div className="flex flex-col gap-3">
                  {d.targets_by_category.map((t) => {
                    const cr = rows.filter((r) => r.allocation.packaging_category === t.category)
                    const cs = split(cr)
                    const al = (lin.allocations.data ?? []).filter((a) => a.status === 'ACTIVE' && a.reporting_period === period && a.packaging_category === t.category).reduce((x, a) => x + a.quantity_kg, 0)
                    const w = (v: number) => `${Math.min(100, (v / t.target_kg) * 100)}%`
                    return (
                      <div key={t.category} className="grid grid-cols-[140px_minmax(0,1fr)_150px] items-center gap-3 text-[12.5px] max-sm:grid-cols-1">
                        <span className="text-fg-2">{CATEGORY_LABEL[t.category] ?? t.category}</span>
                        <span className="flex h-3 overflow-hidden rounded bg-surface-2"><span style={{ width: w(cs.verified), background: 'var(--c1)' }} /><span style={{ width: w(cs.pending), background: 'var(--c3)' }} /><span style={{ width: w(cs.concern), background: 'var(--c5)' }} /></span>
                        <span className="tnum text-right">{num1(al)} / {num1(t.target_kg)} kg</span>
                      </div>
                    )
                  })}
                  <div className="flex flex-wrap gap-4 text-xs text-fg-2">
                    <span className="flex items-center gap-1.5"><i className="size-2.5 rounded-sm" style={{ background: 'var(--c1)' }} />NGO-verified</span>
                    <span className="flex items-center gap-1.5"><i className="size-2.5 rounded-sm" style={{ background: 'var(--c3)' }} />Awaiting review</span>
                    <span className="flex items-center gap-1.5"><i className="size-2.5 rounded-sm" style={{ background: 'var(--c5)' }} />Flagged / rejected</span>
                    <span className="flex items-center gap-1.5"><i className="size-2.5 rounded-sm border border-line-2 bg-surface-2" />Remaining to target</span>
                  </div>
                </div>
              )}
              {lin.error && <ErrorState error={lin.error} onRetry={lin.refetch} />}
            </Panel>
          </div>
        )
      }}</QueryState>
    </>
  )
}

/* ─────────────── Obligations & targets ─────────────── */
const targetSchema = z.object({ reporting_period: z.string().regex(/^FY\d{4}-\d{2}$/, 'Format FY2026-27'), packaging_category: z.string(), target_kg: kgField('Target'), source_note: z.string().max(300).optional() })
export function EprObligations() {
  const targets = useTargets()
  const allocations = useAllocations()
  const [editing, setEditing] = React.useState<z.infer<typeof targetSchema> | null>(null)
  const form = useForm<z.infer<typeof targetSchema>>({ resolver: zodResolver(targetSchema) })
  React.useEffect(() => { if (editing) form.reset(editing) }, [editing, form])
  const m = useApiMutation((v: z.infer<typeof targetSchema>) => eprApi.upsertTarget({ ...v, target_kg: Number(v.target_kg), source_note: v.source_note || undefined }), { invalidate: [K.targets, ['epr']], success: 'Target saved', onSuccess: () => setEditing(null) })
  const allocated = (period: string, cat: string) => (allocations.data ?? []).filter((a) => a.status === 'ACTIVE' && a.reporting_period === period && a.packaging_category === cat).reduce((s, a) => s + a.quantity_kg, 0)
  return (
    <>
      <PageHeader title="Obligations & targets" description="Your self-declared recycling targets by reporting period and packaging category. ReLoop stores what you enter; it does not compute statutory obligations."
        actions={<Button onClick={() => setEditing({ reporting_period: currentReportingPeriod(), packaging_category: 'CAT_I', target_kg: '', source_note: '' })}><Target />Add or update target</Button>} />
      <Panel flush footer={<SourceLine source="ReLoop API · /epr/targets, /epr/allocations" />}>
        <QueryState query={targets}>{(T) => (
          <DataTable label="Targets" rows={T} rowKey={(t) => t.id} onRowClick={(t) => setEditing({ reporting_period: t.reporting_period, packaging_category: t.packaging_category, target_kg: String(t.target_kg), source_note: t.source_note ?? '' })}
            empty={{ title: 'No targets yet' }}
            columns={[
              { key: 'p', header: 'Period', cell: (t) => t.reporting_period, sortValue: (t) => t.reporting_period },
              { key: 'c', header: 'Category', cell: (t) => CATEGORY_LABEL[t.packaging_category] ?? t.packaging_category },
              { key: 't', header: 'Target', numeric: true, cell: (t) => num1(t.target_kg), sortValue: (t) => t.target_kg },
              { key: 'a', header: 'Allocated', numeric: true, cell: (t) => num1(allocated(t.reporting_period, t.packaging_category)) },
              { key: 'r', header: 'Remaining', numeric: true, cell: (t) => <b>{num1(Math.max(0, t.target_kg - allocated(t.reporting_period, t.packaging_category)))}</b> },
              { key: 'cv', header: 'Coverage', numeric: true, cell: (t) => pct((allocated(t.reporting_period, t.packaging_category) / t.target_kg) * 100) },
              { key: 'n', header: 'Source note', cell: (t) => <span className="text-xs">{t.source_note ?? '—'}</span> },
            ]} />
        )}</QueryState>
      </Panel>
      <Note className="mt-4">Statutory targets depend on your CPCB registration, packaging placed on the market and the current EPR Guidelines for Plastic Packaging. Confirm figures with your compliance adviser.</Note>
      <Dialog open={!!editing} onOpenChange={(o) => !o && setEditing(null)}>
        <DialogContent title="Self-declared target" description="Saving a target for an existing period and category replaces it."
          footer={<><Button variant="outline" onClick={() => setEditing(null)}>Cancel</Button><Button loading={m.isPending} onClick={form.handleSubmit((v) => m.mutate(v))}>Save target</Button></>}>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field label="Reporting period" htmlFor="t-p" required error={form.formState.errors.reporting_period?.message}><Input id="t-p" {...form.register('reporting_period')} /></Field>
            <Field label="Category" htmlFor="t-c"><Select id="t-c" {...form.register('packaging_category')}>{Object.entries(CATEGORY_LABEL).map(([k, l]) => <option key={k} value={k}>{l}</option>)}</Select></Field>
            <Field label="Target (kg)" htmlFor="t-k" required error={form.formState.errors.target_kg?.message}><Input id="t-k" inputMode="decimal" {...form.register('target_kg')} /></Field>
            <Field label="Source note" htmlFor="t-n"><Input id="t-n" placeholder="e.g. FY26 EPR plan v2" {...form.register('source_note')} /></Field>
          </div>
          {m.error && <Note tone="bad">{m.error.message}</Note>}
        </DialogContent>
      </Dialog>
    </>
  )
}

