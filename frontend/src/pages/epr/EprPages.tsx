/* ─────────────── Reports ─────────────── */
export function EprReports() {
  const [period, setPeriod] = React.useState(currentReportingPeriod())
  const lin = useAllocationLineage()
  const targets = useTargets()
  const certs = useEprCertificates()
  const A = (lin.allocations.data ?? []).filter((a) => a.reporting_period === period)
  const T = (targets.data ?? []).filter((t) => t.reporting_period === period)
  const cats = [...new Set([...T.map((t) => t.packaging_category), ...A.map((a) => a.packaging_category)])]
  const ready = !lin.loading && !lin.error && targets.isSuccess
  const summary = cats.map((c) => {
    const act = A.filter((a) => a.status === 'ACTIVE' && a.packaging_category === c)
    const s = split(lin.rows.filter((r) => act.some((a) => a.id === r.allocation.id)))
    return { c, target: T.find((t) => t.packaging_category === c)?.target_kg ?? null, allocated: act.reduce((x, a) => x + a.quantity_kg, 0), ...s }
  })
  const exportSummary = () => downloadCsv(`reloop-epr-summary-${period}.csv`, [['period', 'category', 'self_declared_target_kg', 'allocated_kg', 'ngo_verified_kg', 'awaiting_review_kg', 'flagged_kg'], ...summary.map((s) => [period, s.c, s.target, s.allocated.toFixed(3), s.verified.toFixed(3), s.pending.toFixed(3), s.concern.toFixed(3)])])
  const exportLedger = () => downloadCsv(`reloop-epr-ledger-${period}.csv`, [['allocation_id', 'recorded_at', 'period', 'category', 'quantity_kg', 'status', 'reverses', 'reason'], ...A.map((a) => [a.id, a.created_at, a.reporting_period, a.packaging_category, a.quantity_kg, a.status, a.reverses_allocation_id, a.reason])])
  const exportLineage = () => downloadCsv(`reloop-epr-lineage-${period}.csv`, [['allocation_id', 'run', 'source_batch', 'attributed_kg', 'ngo_decision'], ...lin.rows.filter((r) => r.allocation.reporting_period === period).map((r) => [r.allocation.id, r.recordCode, r.batchCode, r.shareKg.toFixed(3), r.decision ?? 'NOT_IN_REVIEW'])])
  return (
    <>
      <PageHeader title="Reports & exports" description="Compliance summaries built from live ReLoop records for your own records and auditors."
        actions={<Select aria-label="Reporting period" value={period} onChange={(e) => setPeriod(e.target.value)} className="w-36">{[...new Set([currentReportingPeriod(), ...(targets.data ?? []).map((t) => t.reporting_period), ...(lin.allocations.data ?? []).map((a) => a.reporting_period)])].map((p) => <option key={p}>{p}</option>)}</Select>} />
      <Note tone="warn" className="mb-4">These exports support, but do not replace, filings on the CPCB EPR portal. The backend’s report endpoint does not generate files yet (audit §5.6), so exports are produced here from the same API data you see on screen.</Note>
      <div className="flex flex-col gap-4">
        <Panel title={`Allocation summary · ${period}`} actions={<Button size="sm" variant="outline" disabled={!ready} onClick={exportSummary}><Download />CSV</Button>} flush>
          {!ready ? <LoadingRows /> : (
            <DataTable label="Summary" rows={summary} rowKey={(s) => s.c} empty={{ title: 'No targets or allocations in this period' }} columns={[
              { key: 'c', header: 'Category', cell: (s) => CATEGORY_LABEL[s.c] ?? s.c },
              { key: 't', header: 'Self-declared target', numeric: true, cell: (s) => num1(s.target) },
              { key: 'a', header: 'Allocated', numeric: true, cell: (s) => num1(s.allocated) },
              { key: 'v', header: 'NGO-verified', numeric: true, cell: (s) => num1(s.verified) },
              { key: 'p', header: 'Awaiting review', numeric: true, cell: (s) => num1(s.pending) },
              { key: 'f', header: 'Flagged', numeric: true, cell: (s) => num1(s.concern) },
            ]} />
          )}
        </Panel>
        <div className="grid gap-4 md:grid-cols-2">
          <Panel title="Allocation ledger" sub={`${A.length} entries in ${period}`} actions={<Button size="sm" variant="outline" disabled={!A.length} onClick={exportLedger}><Download />CSV</Button>}>
            <KV rows={[['Active', A.filter((a) => a.status === 'ACTIVE').length], ['Reversed / reversal entries', A.filter((a) => a.status !== 'ACTIVE').length]]} />
          </Panel>
          <Panel title="Source-batch lineage" sub="Allocation → run → batch with NGO decision" actions={<Button size="sm" variant="outline" disabled={!ready || !lin.rows.length} onClick={exportLineage}><Download />CSV</Button>}>
            <KV rows={[['Lineage rows', lin.rows.filter((r) => r.allocation.reporting_period === period).length], ['Certificate references', certs.data?.length ?? '…']]} />
          </Panel>
        </div>
      </div>
    </>
  )
}
